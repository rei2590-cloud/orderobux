-- REI ROBUX database setup for Supabase
-- Run this entire file once in Supabase Dashboard > SQL Editor.
-- Existing rows are preserved; the stock row is only inserted when missing.

create table if not exists public.robux_stock (
  id integer primary key,
  initial_stock bigint not null default 0 check (initial_stock >= 0),
  available_stock bigint not null default 0 check (available_stock >= 0),
  updated_at timestamptz not null default now(),
  constraint robux_stock_singleton check (id = 1)
);

create table if not exists public.robux_orders (
  id bigint generated by default as identity primary key,
  username text not null,
  display_name text,
  robux_amount integer not null check (robux_amount > 0),
  status text not null default 'pending' check (status in ('pending', 'completed')),
  created_at timestamptz not null default now()
);

insert into public.robux_stock (id, initial_stock, available_stock)
values (1, 0, 0)
on conflict (id) do nothing;

create index if not exists robux_orders_created_at_idx
  on public.robux_orders (created_at desc);
create index if not exists robux_orders_status_idx
  on public.robux_orders (status);

-- The function locks both records so two simultaneous completions cannot
-- spend the same stock. Calling it twice for one completed order is harmless.
create or replace function public.complete_robux_order(p_order_id bigint)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_order public.robux_orders%rowtype;
  v_stock public.robux_stock%rowtype;
begin
  select * into v_order
  from public.robux_orders
  where id = p_order_id
  for update;

  if not found then
    raise exception 'Pesanan tidak ditemukan';
  end if;

  select * into v_stock
  from public.robux_stock
  where id = 1
  for update;

  if not found then
    raise exception 'Data stok belum tersedia';
  end if;

  if v_order.status = 'completed' then
    return v_stock.available_stock;
  end if;

  if v_order.robux_amount > v_stock.available_stock then
    raise exception 'Stok tidak cukup untuk menyelesaikan pesanan ini';
  end if;

  update public.robux_stock
  set available_stock = available_stock - v_order.robux_amount,
      updated_at = now()
  where id = 1
  returning * into v_stock;

  update public.robux_orders
  set status = 'completed'
  where id = p_order_id;

  return v_stock.available_stock;
end;
$$;

-- All database access is performed server-side with the service-role key.
alter table public.robux_stock enable row level security;
alter table public.robux_orders enable row level security;

revoke all on function public.complete_robux_order(bigint) from public;
revoke all on function public.complete_robux_order(bigint) from anon, authenticated;
grant execute on function public.complete_robux_order(bigint) to service_role;
